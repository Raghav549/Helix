"""Synthetic visual-data generation and a trainable visual attribute encoder.

The classifier is independently trained from random initialization on HELIX's
physically rendered primitives. Its labels and probabilities are only validated
for that synthetic domain; predictions on arbitrary photos are uncalibrated.
"""
from __future__ import annotations
from dataclasses import asdict
import hashlib
import json
import os
import random
import time
from typing import List
import numpy as np
from PIL import Image, ImageOps, ImageStat
import torch
import torch.nn as nn
import torch.nn.functional as F
from helix.physics import Scene, render_scene
from helix.runtime import configure_threads

COLORS = ['red', 'green', 'blue']
SHAPES = ['sphere', 'cube']
POSITIONS = ['left', 'center', 'right']


def make_scenes(count: int, seed: int, size: int = 32):
    if not 1 <= count <= 10000:
        raise ValueError('count must be 1..10000')
    rng = random.Random(seed)
    pixels, captions, labels, scenes = [], [], [], []
    for _ in range(count):
        color, shape, pos = rng.choice(COLORS), rng.choice(SHAPES), rng.choice(POSITIONS)
        scene = Scene(shape, color, pos, rng.choice(['matte', 'glossy']),
                      rng.choice(['left', 'right']), rng.uniform(34, 56), size)
        image, _ = render_scene(scene)
        pixels.append(np.asarray(image, dtype=np.uint8))
        captions.append(f'A {scene.material} {color} {shape} on the {pos}, light from the {scene.light}.')
        labels.append([COLORS.index(color), SHAPES.index(shape), POSITIONS.index(pos)])
        scenes.append(asdict(scene))
    arrays = np.stack(pixels)
    manifest = {'generator': 'HELIX physics renderer v1', 'seed': seed, 'count': count,
                'resolution': size, 'license': 'MIT',
                'pixels_sha256': hashlib.sha256(arrays.tobytes()).hexdigest(),
                'caption_sha256': hashlib.sha256('\n'.join(captions).encode()).hexdigest(),
                'notes': 'Synthetic scenes generated by HELIX; no external images or pretrained weights.'}
    return torch.from_numpy(arrays.copy()).permute(0, 3, 1, 2).float() / 127.5 - 1, captions, torch.tensor(labels), manifest


class AttributeVision(nn.Module):
    def __init__(self):
        super().__init__()
        self.features = nn.Sequential(
            nn.Conv2d(3, 16, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
            nn.Conv2d(16, 32, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
            nn.Conv2d(32, 48, 3, padding=1), nn.ReLU(), nn.MaxPool2d(2),
            nn.AdaptiveAvgPool2d((4, 4)), nn.Flatten(), nn.Linear(48*4*4, 96), nn.ReLU())
        self.color = nn.Linear(96, len(COLORS))
        self.shape = nn.Linear(96, len(SHAPES))
        self.position = nn.Linear(96, len(POSITIONS))

    def forward(self, images):
        z = self.features(images)
        return self.color(z), self.shape(z), self.position(z)


@torch.no_grad()
def evaluate_vision(model, images, labels, device='cpu'):
    model.eval()
    logits = model(images.to(device))
    labels = labels.to(device)
    accuracy = [float((logit.argmax(-1) == labels[:, i]).float().mean()) for i, logit in enumerate(logits)]
    joint = torch.stack([logit.argmax(-1) == labels[:, i] for i, logit in enumerate(logits)]).all(0).float().mean()
    return {'color_accuracy': round(accuracy[0], 4), 'shape_accuracy': round(accuracy[1], 4),
            'position_accuracy': round(accuracy[2], 4), 'all_attributes_accuracy': round(float(joint), 4),
            'examples': len(labels), 'domain': 'held-out HELIX-rendered scenes; not natural photos'}


def train_visual(out_dir: str, *, train_count: int = 240, val_count: int = 90,
                 steps: int = 300, batch_size: int = 24, seed: int = 1337, size: int = 32) -> dict:
    if min(steps, batch_size) < 1:
        raise ValueError('steps and batch size must be positive')
    configure_threads()
    torch.manual_seed(seed)
    train_x, _, train_y, train_manifest = make_scenes(train_count, seed, size)
    val_x, _, val_y, val_manifest = make_scenes(val_count, seed + 100_000, size)
    # Ensure the held-out bitmap collection does not share exact images.
    train_hashes = {hashlib.sha256(x.numpy().tobytes()).digest() for x in train_x}
    if any(hashlib.sha256(x.numpy().tobytes()).digest() in train_hashes for x in val_x):
        raise ValueError('exact image overlap between train and holdout')
    model = AttributeVision()
    opt = torch.optim.AdamW(model.parameters(), lr=1e-3)
    os.makedirs(out_dir, exist_ok=True)
    start = time.perf_counter()
    losses = []
    for step in range(steps):
        model.train()
        idx = torch.randint(0, train_count, (batch_size,))
        outputs = model(train_x[idx])
        loss = sum(F.cross_entropy(out, train_y[idx, i]) for i, out in enumerate(outputs))
        opt.zero_grad(set_to_none=True)
        loss.backward()
        opt.step()
        if step % 50 == 0 or step == steps - 1:
            losses.append({'step': step + 1, 'loss': round(float(loss.item()), 6)})
            print(f'[vision] step {step + 1}/{steps}: loss {loss.item():.4f}')
    evaluation = evaluate_vision(model, val_x, val_y)
    torch.save(model.state_dict(), os.path.join(out_dir, 'ckpt-final.pt'))
    metrics = {'stage': 'visual_attributes', 'initialization': 'random', 'steps': steps,
               'batch_size': batch_size, 'seed': seed, 'parameters': sum(p.numel() for p in model.parameters()),
               'elapsed_s': round(time.perf_counter()-start, 3), 'training_loss_samples': losses,
               'heldout': evaluation, 'train_manifest': train_manifest, 'val_manifest': val_manifest}
    with open(os.path.join(out_dir, 'metrics.json'), 'w', encoding='utf-8') as f:
        json.dump(metrics, f, indent=2)
    print(f'[vision] held-out {evaluation}')
    return metrics


def load_visual(path: str):
    model = AttributeVision()
    model.load_state_dict(torch.load(path, map_location='cpu', weights_only=True))
    return model.eval()


def inspect_image(image: Image.Image, model: AttributeVision | None = None) -> dict:
    image = ImageOps.exif_transpose(image).convert('RGB')
    if image.width * image.height > 16_000_000:
        raise ValueError('image exceeds 16 megapixels')
    avg = ImageStat.Stat(image.resize((32, 32))).mean
    gray = np.asarray(image.resize((8, 8)).convert('L'), dtype=np.uint8)
    bits = (gray > gray.mean()).reshape(-1)
    result = {'width': image.width, 'height': image.height,
              'mean_rgb': [round(v, 1) for v in avg],
              'average_hash': f'{sum(int(bit) << i for i, bit in enumerate(bits)):016x}',
              'metadata_note': 'Pixel measurements are computed; classifier predictions are synthetic-domain only.'}
    if model is not None:
        arr = np.asarray(image.resize((32, 32)), dtype=np.float32)
        tensor = torch.from_numpy(arr.copy()).permute(2, 0, 1).unsqueeze(0) / 127.5 - 1
        with torch.no_grad():
            outputs = model(tensor)
        pred = {}
        for key, classes, logits in zip(('color', 'shape', 'position'), (COLORS, SHAPES, POSITIONS), outputs):
            prob = torch.softmax(logits[0], dim=-1)
            idx = int(prob.argmax())
            pred[key] = {'label': classes[idx], 'confidence_uncalibrated': round(float(prob[idx]), 4)}
        result['synthetic_domain_predictions'] = pred
        result['warning'] = 'Not validated on natural photographs; do not treat these labels as factual.'
    return result
